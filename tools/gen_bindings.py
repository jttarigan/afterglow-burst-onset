#!/usr/bin/env python3
"""Generate the kernel binding table from slangc -reflection-json output.
Copied from NeonTide/tools/gen_bindings.py (commit 3dc7266), namespace renamed (D19).

Usage: gen_bindings.py -o KernelBindings.gen.h --spirv a.spirv.json ... [--metal a.metal.json ...]

For every kernel (entry point named after its file) the table lists each resource with its
kind, Vulkan binding and Metal index, plus the push-constant block size and thread-group size.
The gfx backends bind by name through this table, so neither backend hard-codes slot numbers.
The script fails if the targets disagree on a kernel's resource list, kinds, push-constant
size or group size (R1).
"""
import argparse
import json
import sys
from pathlib import Path

KINDS = ("SampledTexture", "StorageTexture", "Sampler", "Buffer", "RWBuffer", "PushConstants")


def struct_size(t):
    for s in t.get("sizes", []):
        if s.get("kind") == "uniform":
            return s.get("value")
    return None


def classify(p):
    t = p["type"]
    k = t.get("kind")
    if k == "samplerState":
        return "Sampler"
    if k == "constantBuffer":
        return "PushConstants"
    if k == "resource":
        shape = t.get("baseShape")
        access = t.get("access", "read")
        if shape == "texture2D":
            return "StorageTexture" if access in ("write", "readWrite") else "SampledTexture"
        if shape in ("structuredBuffer", "byteAddressBuffer"):
            return "RWBuffer" if access in ("write", "readWrite") else "Buffer"
    raise SystemExit(f"unsupported parameter {p['name']}: {t}")


def load(path):
    doc = json.loads(Path(path).read_text(encoding="utf-8"))
    name = Path(path).name.split(".")[0]
    eps = [e for e in doc.get("entryPoints", []) if e.get("name") == name]
    if len(eps) != 1:
        raise SystemExit(f"{path}: expected one entry point named '{name}'")
    group = eps[0].get("threadGroupSize", [1, 1, 1])
    res = []
    push = 0
    for p in doc.get("parameters", []):
        kind = classify(p)
        b = p.get("binding") or p["type"].get("containerVarLayout", {}).get("binding", {})
        if kind == "PushConstants":
            push = struct_size(p["type"]["elementType"])
        res.append({"name": p["name"], "kind": kind, "index": b.get("index"), "bkind": b.get("kind")})
    return name, {"group": group, "push": push, "res": res}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--output", required=True)
    ap.add_argument("--spirv", nargs="+", required=True)
    ap.add_argument("--metal", nargs="*", default=[])
    args = ap.parse_args()

    spv = dict(load(p) for p in args.spirv)
    mtl = dict(load(p) for p in args.metal)
    for name, m in mtl.items():
        s = spv.get(name)
        if s is None:
            raise SystemExit(f"kernel {name} reflected for Metal but not SPIR-V")
        sk = [(r["name"], r["kind"]) for r in s["res"]]
        mk = [(r["name"], r["kind"]) for r in m["res"]]
        if sk != mk or s["push"] != m["push"] or s["group"] != m["group"]:
            raise SystemExit(f"BINDING MISMATCH for {name}:\n  spirv: {s}\n  metal: {m}")

    lines = []
    w = lines.append
    w("// GENERATED by tools/gen_bindings.py from Slang reflection. Do not edit.")
    w("#pragma once")
    w("#include <cstdint>")
    w("")
    w("namespace ag::gen {")
    w("")
    w("enum class BindKind : std::uint8_t { " + ", ".join(KINDS) + " };")
    w("inline constexpr std::uint32_t kNoSlot = 0xFFFFFFFFu;")
    w("struct KernelBinding { const char* name; BindKind kind; std::uint32_t vkBinding; std::uint32_t mtlIndex; };")
    w("struct KernelInfo {")
    w("    const char* name;")
    w("    const KernelBinding* bindings;")
    w("    std::uint32_t bindingCount;")
    w("    std::uint32_t pushBytes;")
    w("    std::uint32_t groupX, groupY, groupZ;")
    w("};")
    w("")
    for name in sorted(spv):
        s = spv[name]
        m = mtl.get(name)
        w(f"inline constexpr KernelBinding kBindings_{name}[] = {{")
        for i, r in enumerate(s["res"]):
            vk = "kNoSlot" if r["kind"] == "PushConstants" else f"{r['index']}u"
            mi = f"{m['res'][i]['index']}u" if m else "kNoSlot"
            w(f'    {{"{r["name"]}", BindKind::{r["kind"]}, {vk}, {mi}}},')
        w("};")
    w("")
    w("inline constexpr KernelInfo kKernels[] = {")
    for name in sorted(spv):
        s = spv[name]
        g = s["group"]
        w(f'    {{"{name}", kBindings_{name}, {len(s["res"])}u, {s["push"] or 0}u, {g[0]}u, {g[1]}u, {g[2]}u}},')
    w("};")
    w(f"inline constexpr std::uint32_t kKernelCount = {len(spv)}u;")
    w(f"inline constexpr std::uint32_t kMaxBindingsPerKernel = {max(len(k['res']) for k in spv.values())}u;")
    w("")
    w("} // namespace ag::gen")
    w("")
    text = "\n".join(lines)
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
